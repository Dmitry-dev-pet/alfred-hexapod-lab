import assert from 'node:assert/strict';
import fs from 'node:fs';
import {CombinedPilot,walkingInput,rightInput} from '../docs/hexapod/freenove-combined-v9/combo-controller.js';
const base=new URL('../docs/hexapod/data/',import.meta.url);
const factory=JSON.parse(fs.readFileSync(new URL('freenove-original-v7-kit.json',base)));
const ref=JSON.parse(fs.readFileSync(new URL('live-v4-gaits-kit.json',base)));
const head=JSON.parse(fs.readFileSync(new URL('live-v5-motion-kit.json',base)));
let n=0;const check=(v,msg)=>{assert.ok(v,msg);n++};
const left={pointer:1,x:-.6,y:.8},right={pointer:2,x:.4,y:-.7};
let inp=walkingInput(left,'turn');check(inp.forward===.8&&inp.turn===.6&&inp.left===0,'left y forward and x yaw');
inp=walkingInput(left,'strafe');check(inp.forward===.8&&inp.left===.6&&inp.turn===0,'left x strafe optional');
check(rightInput(right,'tilt').body.roll===.4&&rightInput(right,'tilt').body.pitch===-.7,'right body tilt');
check(rightInput(right,'shift').body.forward===-.7&&rightInput(right,'shift').body.left===-.4,'right body shift');
check(rightInput(right,'head').head.yaw===.4&&rightInput(right,'head').head.pitch===-.7,'right head');
check(rightInput({pointer:null,x:0,y:0},'head')===null,'right release leaves position');
assert.throws(()=>walkingInput(left,'invalid'));n++;
assert.throws(()=>rightInput(right,'invalid'));n++;
const pilot=new CombinedPilot(factory,ref,head);
pilot.drive(.8,0,.5);pilot.setRight(rightInput(right,'tilt'));
for(let i=0;i<65;i++)pilot.tick(.016);
let p=pilot.tick(.016);
check(p.y>0&&p.yaw>0&&p.body.roll>.3&&p.body.pitch<-.6,'walk+turn+body tilt simultaneously');
check(p.q.length===20&&p.q.every(Number.isFinite),'20 joint targets finite');
check(p.q.slice(0,18).every(v=>Math.abs(v)<=2.4+1e-8),'bounded legs');
check(p.combinedPreview&&p.kinematic,'not a physics claim');
check(p.rootOffsetWorld.length===3&&p.bodyRotvecWorld.length===3,'root pose');
const initial=p.y;
pilot.setRight(rightInput({pointer:2,x:.5,y:.5},'head'));
for(let i=0;i<65;i++)pilot.tick(.016);
p=pilot.tick(.016);check(p.y>initial&&Math.abs(p.q[18]-factory.q_home[18])>.04&&Math.abs(p.q[19]-factory.q_home[19])>.04,'walk+head yaw/pitch');
check(Math.abs(p.head.yaw-.5)<.01&&Math.abs(p.head.pitch-.5)<.01,'head hold target');
for(let i=0;i<30;i++)pilot.tick(.016);check(Math.abs(pilot.tick(.016).head.yaw-.5)<.01,'release keeps head position');
pilot.setRight(rightInput({pointer:3,x:.6,y:-.5},'shift'));
for(let i=0;i<60;i++)pilot.tick(.016);
p=pilot.tick(.016);check(p.body.forward<-.49&&p.body.left<-.59&&p.head.yaw>.49,'head and body shift coexist with walking');
check(Math.abs(p.rootOffsetWorld[0])>.005,'body shift changes pose');
check(p.q.every(Number.isFinite),'mixed no NaNs');
pilot.resetPose();for(let i=0;i<100;i++)pilot.tick(.016);
p=pilot.tick(.016);check(Math.abs(p.head.yaw)<1e-9&&Math.abs(p.body.roll)<1e-9,'right neutral resets pose without walk');
check(p.y>initial,'locomotion not stopped by resetting pose');
pilot.stop();for(let i=0;i<100;i++)pilot.tick(.016);
p=pilot.tick(.016);check(p.command.forward===0&&p.command.turn===0,'stop clears locomotion');
check(Math.abs(p.head.yaw)<1e-9,'stop clears head');
for(const gait of ['wave','tripod']){pilot.setGait(gait);pilot.drive(.6,0,-.4);for(let i=0;i<40;i++)pilot.tick(.016);p=pilot.tick(.016);check(p.q.every(Number.isFinite),gait+' continuous');}
console.log('Combined dual-stick V9',n,'assertions PASS');
