import assert from 'node:assert/strict';
import fs from 'node:fs';
import {GroundLock,rigidFitXY,transformFoot} from '../docs/hexapod/freenove-grounded-v11/ground-lock.js';
import {PlantedCombinedPilot,plantedYawRow} from '../docs/hexapod/freenove-grounded-v11/planted-controller.js';
const base=new URL('../docs/hexapod/data/',import.meta.url);
const factory=JSON.parse(fs.readFileSync(new URL('freenove-original-v7-kit.json',base)));
const ref=JSON.parse(fs.readFileSync(new URL('live-v4-gaits-kit.json',base)));
const head=JSON.parse(fs.readFileSync(new URL('live-v5-motion-kit.json',base)));
const kit=JSON.parse(fs.readFileSync(new URL('../docs/hexapod/freenove-grounded-v11/planted-body-yaw-kit.json',import.meta.url)));
assert.equal(plantedYawRow(kit,0).length,20);
assert.deepEqual(plantedYawRow(kit,15),kit.rows['15']);
assert.deepEqual(plantedYawRow(kit,-15),kit.rows['-15']);
const feet=Object.fromEntries(Object.entries(kit.ground_anchors_xyz_m).map(([n,a])=>[n,{x:a[0],y:a[1],z:a[2]}]));
const lock=new GroundLock(kit);assert.equal(lock.step(feet).stanceCount,6);
const translated={...feet};for(const n in feet)translated[n]={...feet[n],x:feet[n].x-.011,y:feet[n].y+.007};
const row=lock.step(translated);
assert.equal(row.stanceCount,6);assert.ok(Math.abs(row.pose.x-.011)<1e-9);assert.ok(Math.abs(row.pose.y+.007)<1e-9);
assert.ok(row.maxSlipMm<1e-6);
const p=new PlantedCombinedPilot(factory,ref,head,kit);p.setBody('yaw',1);for(let j=0;j<160;j++)p.tick(.016);
let state=p.tick(.016);assert.ok(Math.abs(state.bodyRotvecWorld[2]-Math.PI/12)<1e-8);assert.ok(state.plantedYaw);
assert.ok(Math.max(...state.q.slice(0,18).map(Math.abs))<2.4);
p.resetPose();for(let j=0;j<160;j++)p.tick(.016);
state=p.tick(.016);assert.ok(Math.abs(state.bodyRotvecWorld[2])<1e-9);
const rigid=rigidFitXY(Object.values(feet).map(x=>({local:x,anchor:transformFoot(x,{x:0,y:0,yaw:.17})})));
assert.ok(Math.abs(rigid.yaw-.17)<1e-8);
const f=fs.readFileSync(new URL('../docs/hexapod/freenove-grounded-v11/app.js',import.meta.url),'utf8');
assert.ok(!f.includes('new THREE.Vector3(s.x,s.y,0)'));assert.ok(f.includes('groundLock.step(toes)'));assert.ok(f.includes('planted-body-yaw-kit.json'));
console.log('V11 planted pose + planar contact lock regression PASS');
