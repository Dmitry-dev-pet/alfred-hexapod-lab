"""Measure foot contact mesh clearances in the unpowered, CAD-derived home pose.

No source CAD assets are copied into git or uploaded as CI artifacts.
Use the same pinned MuJoCo source generated by hexlab.cad_mujoco_v04.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hexlab.cad_mujoco_v04 import DEFAULT_CACHE, build


def mesh_geom_world_z(model, data, geom_id: int) -> tuple[float,float]:
    import numpy as np
    mesh_id = int(model.geom_dataid[geom_id])
    if mesh_id < 0:
        raise ValueError("Not a mesh")
    vert_start = int(model.mesh_vertadr[mesh_id])
    nvert = int(model.mesh_vertnum[mesh_id])
    verts = model.mesh_vert[vert_start:vert_start + nvert]
    rot = data.geom_xmat[geom_id].reshape((3,3))
    xyz = verts @ rot.T + data.geom_xpos[geom_id]
    return float(xyz[:,2].min()), float(xyz[:,2].max())


def audit(scenario: str = "nominal", *, cache: Path = DEFAULT_CACHE) -> dict:
    import mujoco
    from hexlab.community_mass_v04 import load, SCENARIOS_PATH
    scene, model_report = build(scenario,cache=cache,offline=True)
    model = mujoco.MjModel.from_xml_path(str(scene))
    data = mujoco.MjData(model)
    mujoco.mj_forward(model,data)
    feet = {}
    for i in range(model.ngeom):
        name = mujoco.mj_id2name(model,mujoco.mjtObj.mjOBJ_GEOM,i) or ""
        if name.startswith("tibia") and "_collision_" in name:
            lo, hi = mesh_geom_world_z(model,data,i)
            feet[name]=[round(lo,6), round(hi,6)]
    if len(feet)!=6:
        raise ValueError(f"Expected 6 CAD tibia collisions, got {feet}")
    lowest = min(x[0] for x in feet.values())
    highest = max(x[0] for x in feet.values())
    return {
      "scenario":scenario,
      "frame":"world+Z; zero is ground plane",
      "root_height_m":round(float(data.xpos[model.body("base_link_2").id][2]),6),
      "feet_min_max_z_m":feet,
      "min_foot_clearance_m":lowest,
      "foot_height_spread_m":round(highest-lowest,6),
      "contact_count_initial":data.ncon,
      "root_height_suggestion_for_2mm_clearance_m":round(float(model.body_pos[model.body("base_link_2").id][2]) - lowest + .002,6),
      "notes":"CAD home pose is unpowered and may not be a valid standing pose; no joint angles or servo calibrations fitted."
    }


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--scenario",default="nominal",choices=["nominal","lower","upper"])
    p.add_argument("--cache",type=Path,default=DEFAULT_CACHE)
    p.add_argument("--out",type=Path)
    args=p.parse_args()
    result=audit(args.scenario,cache=args.cache)
    if args.out:
        args.out.parent.mkdir(parents=True,exist_ok=True)
        args.out.write_text(json.dumps(result,indent=2,ensure_ascii=False)+"\n")
    print(json.dumps(result,indent=2,ensure_ascii=False))

if __name__=="__main__":
    main()
