#!/usr/bin/env python3
"""Pinned V11 Freenove CAD30 **free-root** physics test, not browser visual alignment.

Exact V11 JS joint targets are generated by generate_targets_v11.mjs. This script
runs MuJoCo mj_step under gravity, collision and explicit bounded PD torques.
It NEVER sets free-base qpos after initialization, never pins feet or sets root yaw.
Original CAD30 source lives in owner's private archive; not redistributed.
"""
from __future__ import annotations
import argparse, hashlib, json, math, time
from pathlib import Path
import mujoco as mj
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
CODES=('ml','bl','br','mr','fr','fl')


def support_margin(com,points):
    """Signed perpendicular distance to geometric contact polygon; not dynamic stability."""
    pts=sorted(set(tuple(map(float,p)) for p in points))
    if len(pts)<3:return None
    def cross(a,b,c):return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
    low=[];up=[]
    for p in pts:
        while len(low)>1 and cross(low[-2],low[-1],p)<=0:low.pop()
        low.append(p)
    for p in pts[::-1]:
        while len(up)>1 and cross(up[-2],up[-1],p)<=0:up.pop()
        up.append(p)
    hull=low[:-1]+up[:-1]
    if len(hull)<3:return None
    return min(cross(a,b,com)/math.hypot(b[0]-a[0],b[1]-a[1]) for a,b in zip(hull,hull[1:]+hull[:1]))


def run_case(scene,kit,ref,targetcase,*,friction_scale=1.,torque_limit=0.7,settle_s=1.0,periodic_samples_s=.02,stop_on_fall=True):
    m=mj.MjModel.from_xml_path(str(scene));d=mj.MjData(m)
    assert (m.nq,m.nmesh,m.nu)==(27,30,20),(m.nq,m.nmesh,m.nu)
    assert m.opt.gravity[2] < -9
    assert math.isclose(m.opt.timestep,.002)
    # Physical source baseline: nominal total mass ~1.8049kg, motor limits .7Nm / .2Nm head
    bodyid=m.body('base_link_2').id;floorid=m.geom('floor').id
    m.geom_friction[floorid,0]*=friction_scale
    # Tibia collision geoms are priority=1, while the floor is priority=0.
    # MuJoCo selects the higher-priority friction; change both to make a genuine sensitivity test.
    for suffix in CODES:
        m.geom_friction[m.geom(f"tibia{suffix}_collision_0").id,0]*=friction_scale
    code_geom={m.geom(f'tibia{suffix}_collision_0').id:suffix for suffix in CODES}
    geom_code={v:k for k,v in code_geom.items()}
    qads=m.jnt_qposadr[m.actuator_trnid[:,0]].astype(int)
    dads=m.jnt_dofadr[m.actuator_trnid[:,0]].astype(int)
    # Assert actuator/motor index 0..19 follows kit q_home order
    assert list(qads)==list(range(7,27)) and list(dads)==list(range(6,26)),(qads,dads)
    home=np.array(kit['q_home'],float)
    d.qpos[:3]=kit['cad_adapter']['neutral_root_xyz_m']
    d.qpos[3:7]=ref['root_quat_wxyz']
    d.qpos[7:]=home
    d.qvel[:]=0
    mj.mj_forward(m,d)
    original_root_xyz=d.xpos[bodyid].copy()
    init_rot=d.xmat[bodyid].reshape(3,3).copy()
    up_vector=init_rot.T @ np.array([0.,0.,1.])
    peak_torque=0.;peak_required=0.;saturated_steps=0;steps=0
    kp,kd=7.0,0.32
    caps=np.array(m.actuator_ctrlrange,float)
    caps[:18,0]=np.maximum(caps[:18,0],-torque_limit)
    caps[:18,1]=np.minimum(caps[:18,1],torque_limit)
    assert np.all(caps[:,0]<caps[:,1])

    def step(q):
        nonlocal peak_torque,peak_required,saturated_steps,steps
        unc=kp*(q-d.qpos[qads])-kd*d.qvel[dads]
        torque=np.clip(unc,caps[:,0],caps[:,1]);d.ctrl[:]=torque
        steps+=1
        saturated_steps+=int(np.any(np.abs(unc)>caps[:,1]+1e-9))
        peak_torque=max(peak_torque,float(np.max(np.abs(torque))))
        peak_required=max(peak_required,float(np.max(np.abs(unc))))
        mj.mj_step(m,d)

    def snapshot(t,command):
        root=np.asarray(d.xpos[bodyid]).copy()
        mat=d.xmat[bodyid].reshape(3,3)
        tilt=math.degrees(math.acos(float(np.clip((mat @ up_vector)[2],-1,1))))
        rdiff=mat @ init_rot.T
        yaw=math.degrees(math.atan2(rdiff[1,0],rdiff[0,0]))
        pairs=[];nonfloor=0;normals={n:0. for n in CODES};points={}
        tangential_speeds=[];normal_total=0.;max_normal=0.;active_speed_contacts=0;slipping_speed_contacts=0
        jacp=np.zeros((3,m.nv));jacr=np.zeros((3,m.nv));force=np.zeros(6)
        for ci in range(d.ncon):
            c=d.contact[ci]
            g1,g2=int(c.geom1),int(c.geom2)
            other=g2 if g1==floorid else g1 if g2==floorid else -1
            if other not in code_geom:
                if other<0:nonfloor+=1
                continue
            name=code_geom[other]
            mj.mj_contactForce(m,d,ci,force)
            normal=max(0,float(force[0]))
            if normal<.0001:continue
            normals[name]+=normal;normal_total+=normal;max_normal=max(max_normal,normal)
            points[name]=np.asarray(c.pos[:2]).copy()
            mj.mj_jac(m,d,jacp,jacr,c.pos,int(m.geom_bodyid[other]))
            v=jacp @ d.qvel
            if normal >= 0.5:  # only substantial loaded contact; avoids near-zero grazing spikes
                speed=float(np.linalg.norm(v[:2]))
                tangential_speeds.append(speed)
                active_speed_contacts+=1
                slipping_speed_contacts+=int(speed>.005)
        active=[name for name,v in normals.items() if v>0.05]
        com=(np.asarray(d.xipos)*np.asarray(m.body_mass)[:,None]).sum(axis=0)/m.body_mass.sum()
        margin=support_margin(com[:2],[points[name] for name in active if name in points]);
        err=np.abs(d.qpos[qads]-command)
        return {'t_s':round(float(t),3),'root_z_m':round(float(root[2]),5),'tilt_deg':round(tilt,3),
                'root_x_m':round(float(root[0]),5),'root_y_m':round(float(root[1]),5),
                'yaw_deg':round(yaw,3),'true_grounded_legs':len(active),'active_legs':active,
                'normal_force_N':round(normal_total,3),'max_contact_normal_force_N':round(max_normal,3),
                'per_leg_Fz_N':{name:round(normals[name],2) for name in CODES},
                'max_contact_point_speed_mm_s':round(max(tangential_speeds,default=0)*1000,3),
                'mean_contact_point_speed_mm_s':round(float(np.mean(tangential_speeds)) *1000 if tangential_speeds else 0,3),
                'loaded_contact_samples':active_speed_contacts,'loaded_contacts_speed_above_5mms':slipping_speed_contacts,
                'support_margin_mm':round(margin*1000,3) if margin is not None else None,
                'non_floor_contacts':nonfloor,'max_joint_tracking_error_rad':round(float(np.max(err)),5)}

    for k in range(round(settle_s/m.opt.timestep)):
        step(home)
    settle=snapshot(0.,home)
    start_xyz=d.xpos[bodyid].copy();startrot=d.xmat[bodyid].reshape(3,3).copy()
    cmd=np.asarray(targetcase['targets_q20'],float)
    spec=targetcase['spec'];dt=.01;dur=spec['duration_s']
    assert len(cmd)==round(dur/dt)+1
    assert cmd.shape[1]==20 and np.all(np.isfinite(cmd))
    prev=0;records=[];fallen=False;reason=None
    n=round(dur/m.opt.timestep)
    sample_every=max(1,int(round(periodic_samples_s/m.opt.timestep)))
    for j in range(n):
        t=j*m.opt.timestep
        ix=t/dt;lo=min(int(ix),len(cmd)-2);f=ix-lo
        qtarget=(1-f)*cmd[lo]+f*cmd[lo+1]
        step(qtarget)
        if (j+1)%sample_every==0 or (j+1)==n:
            snap=snapshot(d.time-settle_s, qtarget);records.append(snap)
            if not np.all(np.isfinite(d.qpos)):
                fallen=True;reason='nonfinite_state';break
            if snap['root_z_m']<.075:
                fallen=True;reason='body_below_75mm';break
            if snap['tilt_deg']>45:
                fallen=True;reason='tilt_above_45deg';break
    # ground truth physics result is free-base MuJoCo integration, not V11 viewport pose
    final=records[-1] if records else settle
    done=not fallen and len(records)>0 and (j+1)==n
    intervals=[r for r in records if r['t_s']<=spec['active_s']+.001]
    is_nontrivial=spec['active_s']>0
    def metric(arr,key,fn,default=None):return fn((v[key] for v in arr)) if arr else default
    slips=[r['max_contact_point_speed_mm_s'] for r in intervals if r['true_grounded_legs']>=1]
    margin=[r['support_margin_mm'] for r in intervals if r['support_margin_mm'] is not None]
    report={
      'id':spec['id'],'gait':spec['gait'],'requested':spec,'model_version':mj.__version__,
      'model_sha256':hashlib.sha256(scene.read_bytes()).hexdigest(),
      'physical_model':'CAD30 nominal with free floating base, six tibia collision meshes, floor friction, 20 motor torques',
      'mass_kg':round(float(m.body_mass.sum()),6),'gravity_m_s2':m.opt.gravity.tolist(),
      'timestep_s':float(m.opt.timestep),'friction_scale':friction_scale,
      'actual_floor_friction':m.geom_friction[floorid].tolist(),
      'actual_tibia_friction':m.geom_friction[next(iter(code_geom))].tolist(),
      'actual_contact_friction':d.contact[0].friction.tolist() if d.ncon else None,
      'torque_cap_leg_Nm':torque_limit,'control_law':'PD tau=clip(7*(qcmd-q)-0.32*qvel, actuator range)',
      'servo_pwm_calibrated':False,'actuator_torque_speed_calibrated':False,
      'settle_s':settle_s,'settle':settle,'duration_simulated_s':round(float(d.time-settle_s),4),
      'completed':done,'fall':fallen,'stop_reason':reason,
      'max_tilt_deg':metric(records,'tilt_deg',max),
      'min_root_height_m':metric(records,'root_z_m',min),
      'final_root_xy_m':[final['root_x_m'],final['root_y_m']],
      'net_xy_from_settle_m':round(float(np.linalg.norm(np.array([final['root_x_m'],final['root_y_m']])-start_xyz[:2])),5),
      'final_root_yaw_deg':final['yaw_deg'],
      'max_abs_motor_torque_Nm':round(peak_torque,4),
      'max_abs_requested_torque_before_saturation_Nm':round(peak_required,4),
      'actuator_saturation_fraction':round(saturated_steps/max(1,steps),5),
      'min_true_grounded_legs':metric(records,'true_grounded_legs',min),
      'avg_true_grounded_legs':round(float(np.mean([r['true_grounded_legs'] for r in intervals])),3) if intervals else None,
      'min_normal_force_N':metric(records,'normal_force_N',min),
      'max_load_bearing_contact_tangential_speed_mm_s':max(slips,default=None),
      'fraction_loaded_contacts_slipping_gt_5mm_s':round(sum(x['loaded_contacts_speed_above_5mms'] for x in intervals)/max(1,sum(x['loaded_contact_samples'] for x in intervals)),4),
      'peak_max_joint_tracking_error_rad':metric(records,'max_joint_tracking_error_rad',max),
      'minimum_signed_contact_support_margin_mm':min(margin,default=None),
      'sampled_non_floor_collisions':max((r['non_floor_contacts'] for r in intervals),default=0),
      'samples':records,
      'no_root_pose_injection':True,'no_foot_welding':True,
      'limitations':['Manufacturer mass distribution and motor torque/speed not calibrated on physical kit',
                     'World toe candidate is CAD mesh extremum, not verified rubber pad',
                     'Contact tangential speed computed at world collision contact points when normal force >=0.5N, not a real experimental measurement',
                     'Signed COM margin geometric only: dynamic feasibility uses actual contact forces, joint torque and free-base motion',
                     'Commands are V11 precomputed JS target angles but PD gains are an explicit *assumed* servo law',
                     'Terrain flat, hard, dry with model collision/friction; no external disturbances or real motor PWM/thermal effects']}
    return report


def summarize(r):
    keys=['id','completed','fall','stop_reason','duration_simulated_s','max_tilt_deg','min_root_height_m',
    'net_xy_from_settle_m','final_root_yaw_deg','max_abs_motor_torque_Nm','actuator_saturation_fraction',
    'min_true_grounded_legs','avg_true_grounded_legs','max_load_bearing_contact_tangential_speed_mm_s','fraction_loaded_contacts_slipping_gt_5mm_s',
    'minimum_signed_contact_support_margin_mm','sampled_non_floor_collisions']
    return {k:r[k] for k in keys}


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--scene',type=Path,default=ROOT/'source/mjcf/scene_local30_nominal.xml')
    p.add_argument('--targets',type=Path,default=HERE/'data/targets_v11.json')
    p.add_argument('--out',type=Path,default=HERE/'results/nominal')
    p.add_argument('--cases',nargs='*')
    p.add_argument('--friction-scale',type=float,default=1.)
    p.add_argument('--torque-cap',type=float,default=.7)
    args=p.parse_args()
    assert .01<=args.friction_scale<=2.
    assert .05<=args.torque_cap<=.7
    t=json.loads(args.targets.read_text());assert t['schema']=='fnk0052-v11-exact-controller-targets-physics-v12'
    k=json.loads((ROOT/'docs/hexapod/data/freenove-original-v7-kit.json').read_text())
    r=json.loads((ROOT/'docs/hexapod/data/live-v4-gaits-kit.json').read_text())
    selected=args.cases or list(t['cases'])
    args.out.mkdir(parents=True,exist_ok=True)
    reports=[]
    for case in selected:
        started=time.perf_counter()
        data=run_case(args.scene,k,r,t['cases'][case],friction_scale=args.friction_scale,torque_limit=args.torque_cap)
        name=case+'.json';(args.out/name).write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
        reports.append(summarize(data))
        print(json.dumps({**summarize(data),'wall_s':round(time.perf_counter()-started,3)},ensure_ascii=False),flush=True)
    (args.out/'summary.json').write_text(json.dumps({
        'schema':'hexapod-cad30-V11-physical-mj_step-20261106','source_scene_sha256':hashlib.sha256(args.scene.read_bytes()).hexdigest(),
        'cases':reports,'free_base':True,'actual_contacts':True,'no_online_browser_physics':True,
        'torque_limit_Nm':args.torque_cap,'friction_scale':args.friction_scale},ensure_ascii=False,indent=2)+'\n')

if __name__=='__main__':main()
